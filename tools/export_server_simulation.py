"""Export the client actor's exact fixed-step logic for headless server simulation.

Rendering and local feedback are replaced by explicit runtime adapters. Gameplay,
collision sensors, character state machines and animation timing stay unchanged.
Run with the matching server repository as the only argument.
"""
from pathlib import Path
import hashlib
import json
import re
import sys

CLIENT = Path(__file__).resolve().parents[1]
SERVER = Path(sys.argv[1]).resolve()
DEST = SERVER / "src/simulation/generated"
DEST.mkdir(parents=True, exist_ok=True)


def function_replace(text, name, replacement):
    pattern = rf"(?m)^(?:static )?func {re.escape(name)}\([^\n]*(?:\n[ \t][^\n]*)*\n?"
    # Bound functions by the next top-level declaration, including multiline signatures.
    match = re.search(rf"(?m)^(?:static )?func {re.escape(name)}\(", text)
    if not match:
        raise ValueError(name)
    end = re.search(r"(?m)^(?=func |static func |var |const |@export)", text[match.end():])
    stop = match.end() + end.start() if end else len(text)
    return text[:match.start()] + replacement.rstrip() + "\n\n\n" + text[stop:]


def transform(text):
    text = text.replace("res://src/game/", "res://src/simulation/generated/")
    text = text.replace("GMNode", "SimulationNode").replace("GMFloor", "SimulationFloor")
    return text


sources = {}
def write(source, target=None, edit=None):
    data = (CLIENT / source).read_text(encoding="utf-8-sig")
    sources[source] = hashlib.sha256(data.encode()).hexdigest()
    if edit:
        data = edit(data)
    path = DEST / (target or source.removeprefix("src/game/"))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("# Generated by tools/export_server_simulation.py; edit the client source.\n" + transform(data), encoding="utf-8")


def actor(text):
    replacements = {
        "_ready": '''func _ready() -> void:
\tsuper._ready()
\tadd_to_group("obj_player")
\tgm_name = "obj_player"
\tGlobals.player = self
\t_apply_character()''',
        "quick_effect": '''func quick_effect(_x: float, _y: float, _spr: String, _fade := true, _direction := 1.0) -> SimulationNode:
\treturn Net.effect_node''',
        "camera_shake": "func camera_shake(_time: int, _magnitude: float, _fade := 0.25) -> void:\n\tpass",
        "frame_texture": "func frame_texture() -> Texture2D:\n\treturn null",
        "_physics_process": "func _physics_process(_delta: float) -> void:\n\tpass",
        "_step_visual_effects": "func _step_visual_effects() -> void:\n\tpass",
        "_gm_draw": "func _gm_draw() -> void:\n\tpass",
        "collision_objects_before": "func collision_objects_before() -> void:\n\tNet.before_player(self)",
        "take_red_ring": "func take_red_ring() -> void:\n\tredRingTimer = 600",
        "taunt1": "func taunt1() -> bool:\n\treturn true",
        "taunt2": "func taunt2() -> bool:\n\treturn true",
    }
    for name, replacement in replacements.items():
        text = function_replace(text, name, replacement)
    return text


write("src/game/player.gd", edit=actor)
write("src/game/gmfloor.gd", "floor.gd", lambda t: t.replace('class_name GMFloor', 'class_name SimulationFloor'))
write("src/game/obj_spring.gd", "spring.gd", lambda t: function_replace(t, "_gm_draw", "func _gm_draw() -> void:\n\tpass"))
write("src/game/maps/zipline.gd", edit=lambda t: function_replace(t.replace("var properties: Dictionary = {}\n",""),"_gm_draw","func _gm_draw() -> void:\n\tpass"))
puppet = (CLIENT / "src/game/obj_player_puppet.gd").read_text(encoding="utf-8-sig")
animations = puppet[puppet.index("const ANIMS"):puppet.index("var master_id")]
(DEST / "obj_player_puppet.gd").write_text("extends RefCounted\n" + animations, encoding="utf-8")
services = '''
var GM: SimulationSprites:
\tget: return p.GM
var Globals: SimulationGlobals:
\tget: return p.Globals
var Net: SimulationNetwork:
\tget: return p.Net
var GameAudio: SimulationAudio:
\tget: return p.GameAudio
'''
for directory in ["survivors", "hunters"]:
    for path in sorted((CLIENT / "src/game" / directory).glob("*.gd")):
        if directory == "hunters" and path.stem not in ["base", "chaos", "exetior", "exeller", "chaos_anims", "exetior_anims", "exeller_anims"]:
            continue
        def edit(text, path=path):
            if path.stem == "base":
                text += services
            for name in re.findall(r"(?m)^func (draw\w*)\(", text):
                text = function_replace(text, name, f"func {name}(_unused = null):\n\tpass")
            if path.stem == "tails":
                start = text.index("\tif character_id == 1:")
                stop = text.index("\n\nfunc ", start) if "\n\nfunc " in text[start:] else text.index("\n\n\nfunc ",start)
                text = text[:start] + text[stop:]
            if directory == "hunters" and re.search(r"(?m)^func emotion_sound\(", text):
                text = function_replace(text,"emotion_sound","func emotion_sound(_slot: int):\n\tpass")
            if path.stem == "exetior":
                text = function_replace(text,"ring_allowed","func ring_allowed() -> bool:\n\treturn Net.host.exetior_rules.ring_allowed(p.position - Vector2(15,15))")
            return text
        write(str(path.relative_to(CLIENT)).replace("\\", "/"), edit=edit)

metadata = json.loads((CLIENT / "assets/gm/sprites.json").read_text(encoding="utf-8-sig"))
for value in metadata.values():
    value["count"] = len(value.pop("frames"))
(DEST / "sprites.json").write_text(json.dumps(metadata, separators=(",", ":")), encoding="utf-8")
(DEST / "manifest.json").write_text(json.dumps(sources, indent=2) + "\n", encoding="utf-8")
(SERVER / "src/net/movement_state.gd").write_text((CLIENT / "src/net/movement_state.gd").read_text(encoding="utf-8-sig"), encoding="utf-8")
print(f"Exported actor simulation from {len(sources)} source files")
